"""
Visualize the CLIP embedding pipeline: manually retained -> curated -> sampled.

The three panels always share one 2D coordinate system:
  PCA  — fitted on the manually retained set, then used to transform later stages
  UMAP — fitted jointly on embeddings from all three stages

Manual and curated embeddings are loaded from NPZ files generated by curate.py.
Embeddings for the sampled images are computed directly from the sample folder.

The legend is rendered with Pillow to improve multilingual label support.

Output:
    data/analysis/{cluster_id}_pipeline_viz_{method}.png
    data/analysis/{cluster_id}_pipeline_viz_{method}.pdf
    data/analysis/{cluster_id}_pipeline_viz_{method}.svg

Usage:
    # Single cluster
    python scripts/clip_viz.py --cluster pilaf_cl

    # All configured clusters
    python scripts/clip_viz.py --all
"""

import argparse
import csv
import numpy as np
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import matplotlib
import matplotlib.pyplot as plt
import matplotlib.font_manager as fm
from matplotlib.offsetbox import AnnotationBbox, OffsetImage
from sklearn.decomposition import PCA

IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp", ".bmp"}
ALL_CLUSTERS    = ["pilaf_cl", "mantou_cl", "samosa_cl", "meatball_cl"]
FONTS_DIR       = Path(__file__).parent.parent / "data" / "cue_references" / "fonts"

# Register project fonts for matplotlib (covers Latin, Cyrillic, Korean, Arabic)
if FONTS_DIR.exists():
    for _ttf in FONTS_DIR.glob("*.ttf"):
        fm.fontManager.addfont(str(_ttf))

matplotlib.rcParams["font.family"]        = "sans-serif"
matplotlib.rcParams["axes.unicode_minus"] = False
matplotlib.rcParams["font.sans-serif"]    = [
    "Noto Sans", "Noto Sans KR", "Noto Sans SC",
    "Noto Sans Arabic", "DejaVu Sans",
]


# -----------------------------------------------------------------------------
# Endonym helpers
# -----------------------------------------------------------------------------

def get_endonyms_from_log(manual_dir, cluster_id, paths):
    """
    Map embedding paths to endonyms using the filter log.
    Falls back to parsing the filename (NNNN_endonym.ext) if log lookup fails.
    """
    log_path = Path(manual_dir) / cluster_id / "filter_log.csv"
    path_to_endonym = {}
    if log_path.exists():
        with open(log_path, "r", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                if row["decision"] == "k":
                    path_to_endonym[row["output_path"]] = row["original_endonym"]

    fname_to_endonym = {Path(op).name: e for op, e in path_to_endonym.items()}

    endonyms = []
    for p in paths:
        endonym = path_to_endonym.get(p)
        if not endonym:
            endonym = fname_to_endonym.get(Path(p).name)
        if not endonym:
            parts   = Path(p).stem.split("_", 1)
            endonym = parts[1] if len(parts) > 1 else "unknown"
        endonyms.append(endonym)
    return endonyms


def endonyms_from_paths(paths):
    """Parse endonym from filename: NNNN_endonym.ext -> endonym."""
    result = []
    for p in paths:
        parts   = Path(p).stem.split("_", 1)
        endonym = parts[1] if len(parts) > 1 else "unknown"
        result.append(endonym)
    return result


# -----------------------------------------------------------------------------
# Embedding computation (only used for final 40)
# -----------------------------------------------------------------------------

def compute_embeddings(images, device="cuda"):
    """Compute CLIP ViT-L-14 embeddings for a list of (path, endonym) pairs."""
    import open_clip
    import torch

    print(f"  Loading CLIP ViT-L-14 on {device}...")
    model, _, preprocess = open_clip.create_model_and_transforms(
        "ViT-L-14", pretrained="openai"
    )
    model = model.to(device).eval()

    embeddings = []
    for i, (img_path, _) in enumerate(images):
        try:
            img = (preprocess(Image.open(img_path).convert("RGB"))
                   .unsqueeze(0).to(device))
            with torch.no_grad():
                feat = model.encode_image(img)
                feat /= feat.norm(dim=-1, keepdim=True)
            embeddings.append(feat.cpu().numpy()[0])
        except Exception as e:
            print(f"  ERROR {img_path.name}: {e}")
            embeddings.append(np.zeros(768))

    return np.array(embeddings)


# -----------------------------------------------------------------------------
# Pillow legend renderer (supports all Unicode scripts)
# -----------------------------------------------------------------------------

def _pick_pil_font(text, fonts):
    """Pick the right Pillow font based on Unicode block of characters."""
    for ch in text:
        cp = ord(ch)
        if 0x0900 <= cp <= 0x097F:                       # Devanagari
            return fonts["devanagari"]
        if (0xAC00 <= cp <= 0xD7AF or
                0x1100 <= cp <= 0x11FF or
                0x3130 <= cp <= 0x318F):                  # Korean Hangul
            return fonts["korean"]
        if 0x0600 <= cp <= 0x06FF:                        # Arabic / Persian
            return fonts["arabic"]
    return fonts["default"]


def render_legend_pillow(endonym_color_pairs, font_size=10):
    """
    Render a legend image using Pillow supporting all scripts.
    Returns numpy RGBA array for OffsetImage, or None if fonts unavailable.
    """
    if not FONTS_DIR.exists():
        return None

    def load_font(name):
        p = FONTS_DIR / name
        return ImageFont.truetype(str(p), font_size) if p.exists() \
               else ImageFont.load_default()

    fonts = {
        "default":    load_font("NotoSans-Bold.ttf"),
        "devanagari": load_font("NotoSansDevanagari-Bold.ttf"),
        "arabic":     load_font("NotoSansArabic-Bold.ttf"),
        "korean":     load_font("NotoSansSC-Bold.ttf"),
    }

    row_h    = font_size + 8
    swatch_w = font_size
    gap      = 6
    pad      = 8

    dummy  = Image.new("RGBA", (1, 1))
    draw_d = ImageDraw.Draw(dummy)
    max_label_w = 0
    for endonym, _ in endonym_color_pairs:
        font = _pick_pil_font(endonym, fonts)
        bbox = draw_d.textbbox((0, 0), endonym, font=font)
        max_label_w = max(max_label_w, bbox[2] - bbox[0])

    img_w = pad + swatch_w + gap + max_label_w + pad
    img_h = pad + row_h * len(endonym_color_pairs) + pad

    img  = Image.new("RGBA", (img_w, img_h), (26, 26, 26, 200))
    draw = ImageDraw.Draw(img)

    for i, (endonym, color) in enumerate(endonym_color_pairs):
        y       = pad + i * row_h
        r, g, b = [int(c * 255) for c in color[:3]]
        draw.rectangle([pad, y + 2, pad + swatch_w, y + 2 + swatch_w],
                       fill=(r, g, b, 255))
        font = _pick_pil_font(endonym, fonts)
        draw.text((pad + swatch_w + gap, y), endonym,
                  font=font, fill=(220, 220, 220, 255))

    return np.array(img)


# -----------------------------------------------------------------------------
# Dimensionality reduction
# -----------------------------------------------------------------------------

def reduce_pca(kept_emb, curated_emb, final_emb):
    """Fit PCA on manual filtered set; transform all others with same axes."""
    pca            = PCA(n_components=2)
    kept_coords    = pca.fit_transform(kept_emb)
    curated_coords = pca.transform(curated_emb)
    final_coords   = pca.transform(final_emb)
    print(f"PCA explained variance: "
          f"PC1={pca.explained_variance_ratio_[0]:.1%}, "
          f"PC2={pca.explained_variance_ratio_[1]:.1%}")
    return kept_coords, curated_coords, final_coords


def reduce_umap(kept_emb, curated_emb, final_emb):
    """Fit UMAP on all embeddings combined for consistent coordinate space."""
    try:
        import umap
    except ImportError:
        raise ImportError("Install umap-learn: pip install umap-learn")

    all_emb    = np.vstack([kept_emb, curated_emb, final_emb])
    reducer    = umap.UMAP(n_components=2, random_state=42)
    all_coords = reducer.fit_transform(all_emb)
    n_kept     = len(kept_emb)
    n_curated  = len(curated_emb)
    return (all_coords[:n_kept],
            all_coords[n_kept:n_kept + n_curated],
            all_coords[n_kept + n_curated:])


# -----------------------------------------------------------------------------
# Plotting
# -----------------------------------------------------------------------------

def plot_three_panels(coords_list, endonyms_list, titles,
                      cluster_id, output_path, method):
    """Plot the three pipeline stages in one shared 2D coordinate system."""

    all_endonyms = sorted(set(e for endonyms in endonyms_list for e in endonyms))
    n            = max(len(all_endonyms), 1)
    tab20_colors = matplotlib.colormaps["tab20"].resampled(n).colors
    color_map    = {e: tab20_colors[i] for i, e in enumerate(all_endonyms)}

    fig, axes = plt.subplots(1, 3, figsize=(21, 7))
    fig.patch.set_facecolor("#0e0e0e")

    all_coords = np.vstack(coords_list)
    x_min, x_max = all_coords[:, 0].min(), all_coords[:, 0].max()
    y_min, y_max = all_coords[:, 1].min(), all_coords[:, 1].max()
    pad_x = (x_max - x_min) * 0.05
    pad_y = (y_max - y_min) * 0.05

    for ax, coords, endonyms, title in zip(axes, coords_list,
                                            endonyms_list, titles):
        ax.set_facecolor("#0e0e0e")
        endonyms_arr = np.array(endonyms)

        for endonym in all_endonyms:
            mask = endonyms_arr == endonym
            if mask.sum() == 0:
                continue
            ax.scatter(coords[mask, 0], coords[mask, 1],
                       c=[color_map[endonym]],
                       alpha=0.75, s=40, edgecolors="none")

        ax.set_xlim(x_min - pad_x, x_max + pad_x)
        ax.set_ylim(y_min - pad_y, y_max + pad_y)
        ax.set_title(f"{title}\n(n={len(endonyms)})",
                     color="white", fontsize=11, pad=8)
        ax.tick_params(colors="#555")
        ax.spines[:].set_color("#333")
        if method == "pca":
            ax.set_xlabel("PC 1", color="#888", fontsize=8)
            ax.set_ylabel("PC 2", color="#888", fontsize=8)
        else:
            ax.set_xlabel("UMAP dimension 1", color="#888", fontsize=8)
            ax.set_ylabel("UMAP dimension 2", color="#888", fontsize=8)

    display_pairs = [(e, color_map[e]) for e in all_endonyms]
    legend_arr    = render_legend_pillow(display_pairs, font_size=10)

    if legend_arr is not None:
        im = OffsetImage(legend_arr, zoom=1.0)
        ab = AnnotationBbox(im, xy=(1.0, 1.0),
                            xycoords="axes fraction",
                            box_alignment=(1.02, 1.0),
                            frameon=False, pad=0)
        axes[-1].add_artist(ab)
    else:
        handles = [plt.Line2D([0], [0], marker="o", color="w",
                              markerfacecolor=color_map[e],
                              markersize=7, label=e)
                   for e in all_endonyms]
        axes[-1].legend(handles=handles, loc="upper right", fontsize=6,
                        framealpha=0.3, facecolor="#1a1a1a",
                        edgecolor="#444", labelcolor="white")

    if method == "pca":
        projection_note = (
            "PCA fitted on manually retained images. "
            "All panels use the same PCA axes."
        )
    else:
        projection_note = (
            "UMAP fitted jointly on all three stages; "
            "all panels use the same 2D embedding."
        )

    fig.suptitle(
        f"{cluster_id} — CLIP embedding pipeline ({method.upper()})\n"
        f"{projection_note}",
        color="white", fontsize=11, y=1.02
    )

    plt.tight_layout()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(output_path, dpi=150, bbox_inches="tight",
                facecolor=fig.get_facecolor())
    print(f"Plot saved to: {output_path}")

    pdf_path = output_path.with_suffix(".pdf")
    svg_path = output_path.with_suffix(".svg")
    plt.savefig(pdf_path, bbox_inches="tight", facecolor=fig.get_facecolor())
    plt.savefig(svg_path, bbox_inches="tight", facecolor=fig.get_facecolor())
    print(f"Also saved: {pdf_path.name}, {svg_path.name}")
    plt.close()


# -----------------------------------------------------------------------------
# Core run function
# -----------------------------------------------------------------------------

def run(args):
    cluster_id = args.cluster
    output_dir = Path(args.analysis_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    print(f"\nCluster: {cluster_id}")

    # ── Load pre-computed manual embeddings ──────────────────────────
    man_emb_path = output_dir / f"{cluster_id}_manual_embeddings.npz"
    if not man_emb_path.exists():
        raise FileNotFoundError(
            f"Manual embeddings not found: {man_emb_path}\n"
            f"Run first: python scripts/curate.py --cluster {cluster_id} --embed")

    man_data      = np.load(man_emb_path, allow_pickle=True)
    kept_emb      = man_data["embeddings"]
    kept_paths    = man_data["paths"].tolist()
    kept_endonyms = get_endonyms_from_log(args.manual_dir, cluster_id, kept_paths)

    # ── Load pre-computed curated embeddings ─────────────────────────
    cur_emb_path = output_dir / f"{cluster_id}_curated_embeddings.npz"
    if not cur_emb_path.exists():
        raise FileNotFoundError(
            f"Curated embeddings not found: {cur_emb_path}\n"
            f"Run first: python scripts/curate.py --cluster {cluster_id}")

    cur_data         = np.load(cur_emb_path, allow_pickle=True)
    curated_emb      = cur_data["embeddings"]
    curated_paths    = cur_data["paths"].tolist()
    curated_endonyms = endonyms_from_paths(curated_paths)

    # ── Compute embeddings for final 40 directly from sample dir ─────
    candidates = sorted(
        p for p in output_dir.glob(f"{cluster_id}_sample_n40*")
        if p.is_dir()
    )
    if not candidates:
        raise FileNotFoundError(
            f"No sample directory found for {cluster_id} in {output_dir}\n"
            f"Run first: python scripts/sample.py --cluster {cluster_id} --copy")
    sample_path = candidates[-1]

    final_images = [
        (f.resolve(), f.stem.split("_", 1)[1] if "_" in f.stem else "unknown")
        for f in sorted(sample_path.iterdir())
        if f.suffix.lower() in IMAGE_EXTENSIONS
    ]

    print(f"  Manually retained : {len(kept_emb)}")
    print(f"  After curation    : {len(curated_emb)}")
    print(f"  Final sample      : {len(final_images)} — computing embeddings...")
    if len(final_images) != 40:
        print(f"  WARNING: expected 40 sampled images, found {len(final_images)}")

    final_emb      = compute_embeddings(final_images, device=args.device)
    final_endonyms = [e for _, e in final_images]

    # ── Reduce to 2D ─────────────────────────────────────────────────
    print(f"Reducing to 2D with {args.method.upper()}...")
    if args.method == "pca":
        kept_coords, curated_coords, final_coords = reduce_pca(
            kept_emb, curated_emb, final_emb)
    else:
        kept_coords, curated_coords, final_coords = reduce_umap(
            kept_emb, curated_emb, final_emb)

    # ── Plot ─────────────────────────────────────────────────────────
    plot_path = output_dir / f"{cluster_id}_pipeline_viz_{args.method}.png"
    plot_three_panels(
        coords_list   = [kept_coords, curated_coords, final_coords],
        endonyms_list = [kept_endonyms, curated_endonyms, final_endonyms],
        titles        = ["Manually Retained", "After Curation", "Final Sample"],
        cluster_id    = cluster_id,
        output_path   = plot_path,
        method        = args.method
    )
    print(f"Done: {cluster_id}")


# -----------------------------------------------------------------------------
# Entry point
# -----------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="Visualize three CLIP embedding pipeline stages in one 2D space")
    parser.add_argument("--cluster",
                        help="Cluster ID e.g. pilaf_cl. "
                             "Required unless --all is set.")
    parser.add_argument("--all",          action="store_true",
                        help="Run for all clusters: " + ", ".join(ALL_CLUSTERS))
    parser.add_argument("--manual-dir",   default="data/manual_filtered")
    parser.add_argument("--analysis-dir", default="data/analysis")
    parser.add_argument("--method",       default="pca",
                        choices=["pca", "umap"])
    parser.add_argument("--device",       default="cuda:1",
                        help="Torch device for sampled-image CLIP embeddings")
    args = parser.parse_args()

    if not args.all and not args.cluster:
        parser.error("Provide --cluster CLUSTER_ID or use --all")

    if args.all:
        for cluster in ALL_CLUSTERS:
            args.cluster = cluster
            try:
                run(args)
            except Exception as e:
                print(f"ERROR processing {cluster}: {e}")
    else:
        run(args)


if __name__ == "__main__":
    main()